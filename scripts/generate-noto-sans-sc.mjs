// Builds src/app/fonts/noto-sans-sc.css: Noto Sans SC (variable, all weights) as self-hosted WOFF2, split into
// unicode-range chunks so a page downloads only the characters it shows. The family name "PGC Noto Sans SC" is
// used only on Chinese pages (globals.css, html:lang(zh)), so English pages never load these files.
// The font files ship with the site (bundled from @fontsource-variable/noto-sans-sc); no Google Fonts CDN.
// License: SIL Open Font License 1.1 — see public/fonts/NotoSansSC-OFL.txt.
// Run: node scripts/generate-noto-sans-sc.mjs
import { readFileSync, writeFileSync } from "node:fs";

const pkg = "noto-sans-sc";
const family = "PGC Noto Sans SC";
const css = readFileSync(`node_modules/@fontsource-variable/${pkg}/wght.css`, "utf8");
const out = ["/* Generated by scripts/generate-noto-sans-sc.mjs — do not edit by hand. */"];
for (const block of css.match(/@font-face\s*{[^}]*}/g)) {
  const file = block.match(/files\/([^)]+\.woff2)/)[1];
  const range = block.match(/unicode-range:\s*([^;]+);/)[1].trim();
  out.push(
    `@font-face{font-family:"${family}";font-style:normal;font-display:swap;font-weight:100 900;` +
      `src:url("../../../node_modules/@fontsource-variable/${pkg}/files/${file}") format("woff2-variations");` +
      `unicode-range:${range}}`,
  );
}
writeFileSync("src/app/fonts/noto-sans-sc.css", out.join("\n") + "\n");
console.log(`wrote ${out.length - 1} @font-face rules`);
